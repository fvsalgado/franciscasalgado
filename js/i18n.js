/* Que língua vai ser usada, antes sequer de a página estar montada. O banner
   de cookies aparece cedo e precisa de saber isto sem esperar pelo resto. */
export function linguaEscolhida() {
  let guardada = null;
  try { guardada = localStorage.getItem('fs-lingua'); } catch { /* modo privado */ }
  if (guardada === 'pt' || guardada === 'en') return guardada;
  return (navigator.language || 'pt').toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

export function criarLingua(aoMudar) {
  const PT = {};
  document.querySelectorAll('[data-t]').forEach((el) => { PT[el.dataset.t] = el.innerHTML; });

  let lingua = linguaEscolhida();

  /* `silencioso` serve o arranque: em inglês há que aplicar já o dicionário,
     mas quem pinta o conteúdo a primeira vez é o base.js, com uma chamada
     explícita. Sem isto a página nascia desenhada duas vezes. */
  function aplicar(l, silencioso = false) {
    lingua = l;
    const dic = l === 'en' ? EN : PT;
    document.querySelectorAll('[data-t]').forEach((el) => {
      const v = dic[el.dataset.t];
      if (v !== undefined) el.innerHTML = v;
    });
    // reescrever o innerHTML apaga a máscara que o partirTitulos põe nos
    // títulos; marcam-se como por partir, e quem repinta trata do resto
    document.querySelectorAll('.ani[data-t]').forEach((el) => { delete el.dataset.partido; });
    document.documentElement.lang = l === 'en' ? 'en' : 'pt-PT';
    const bt = document.getElementById('btLang');
    if (bt) bt.textContent = l === 'en' ? 'PT' : 'EN';
    try { localStorage.setItem('fs-lingua', l); } catch { /* modo privado */ }
    if (silencioso) return;
    document.dispatchEvent(new CustomEvent('fs:lingua', { detail: l }));
    aoMudar?.(l);
  }

  document.addEventListener('click', (e) => {
    if (e.target.closest('#btLang')) aplicar(lingua === 'pt' ? 'en' : 'pt');
  });

  if (lingua === 'en') aplicar('en', true);
  return { lingua: () => lingua, aplicar };
}
